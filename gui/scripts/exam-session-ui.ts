import { app, BrowserWindow } from 'electron'
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { tmpdir } from 'node:os'
import assert from 'node:assert/strict'
const root = mkdtempSync(join(tmpdir(), 'heimdall-session-ui-')), out = resolve('../docs/reviews/evidence/T221')
mkdirSync(out, { recursive: true }); app.setPath('userData', join(root, 'profile')); app.disableHardwareAcceleration(); app.commandLine.appendSwitch('force-device-scale-factor', '1')
const css = readdirSync('out/renderer/assets').find(file => file.startsWith('index-') && file.endsWith('.css'))!
writeFileSync(join(root, 'style.css'), readFileSync(join('out/renderer/assets', css))); writeFileSync(join(root, 'fixture.js'), readFileSync('/tmp/heimdall-session-fixture.js'))
writeFileSync(join(root, 'index.html'), '<html><head><meta charset="utf-8"><link rel="stylesheet" href="style.css"></head><body><div id="root"></div><script src="fixture.js"></script></body></html>')
app.whenReady().then(async () => {
 const win = new BrowserWindow({ width: 1366, height: 768, show: false, webPreferences: { contextIsolation: true, nodeIntegration: false, offscreen: true } }), errors: string[] = []
 win.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message) })
 const js = (code: string) => win.webContents.executeJavaScript(code), wait = () => new Promise(resolve => setTimeout(resolve, 250))
 const click = async (text: string) => { await js(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(text)});if(!b || b.disabled)throw Error('Missing '+${JSON.stringify(text)});b.click()})()`); await wait() }
 const shot = async (name: string) => { if (process.env.SESSION_UI_CAPTURE === '0') return; await wait(); writeFileSync(join(out, `${name}.png`), (await win.webContents.capturePage()).toPNG()) }
 await win.loadFile(join(root, 'index.html')); await wait()
 assert.equal(await js(`document.querySelector('.matrix-viewport').scrollWidth > 0`), true)
 assert.equal(await js(`document.body.innerText.includes('Mejor nota · Vuelta 1')`), true)
 assert.equal(await js(`document.body.innerText.includes('Última: 5,0')`), true)
 await shot('matrix-active-1366')
 await click('Pausar')
 assert.equal(await js(`document.body.innerText.includes('Pausado')`), true)
 assert.equal(await js(`document.querySelector('[role="alertdialog"]') === null`), true)
 assert.equal(await js(`document.body.innerText.includes('Reanudar')`), true)
 await shot('matrix-paused-1366')
 await click('Reanudar')
 assert.equal(await js(`document.querySelector('.matrix-viewport') !== null`), true)
 await js(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()==='Finalizar examen');b.click();b.click()})()`); await wait()
 assert.equal(await js('window.examFixture.calls'), 1)
 assert.equal(await js(`document.querySelector('[role="alertdialog"]') === null`), true)
 assert.equal(await js(`document.querySelector('[data-testid="final-grades"]') !== null`), true)
 assert.equal(await js(`document.querySelector('.matrix-viewport') === null`), true)
 assert.equal(await js(`document.body.innerText.includes('Vuelta') || document.body.innerText.includes('vueltas') || document.body.innerText.includes('Próxima corrección')`), false)
 assert.equal(await js(`document.querySelector('table').rows.length`), 15)
 await js('window.examFixture.changeThreshold()'); await wait()
 assert.equal(await js(`document.querySelector('table').rows[2].cells[1].textContent`), '8,3')
 assert.equal(await js(`document.querySelector('table').rows[1].cells[1].textContent`), '10,0')
 assert.equal(await js(`(()=>{const r=document.querySelector('table').getBoundingClientRect();return r.bottom <= innerHeight})()`), true)
 await shot('final-grades-1366')
 win.setSize(1920, 1080); await js('window.examFixture.theme(true)'); await wait(); await shot('final-grades-1920')
 assert.equal(await js('document.documentElement.scrollWidth <= innerWidth'), true)
 win.setSize(1366, 768); await js('window.examFixture.theme(false)'); await wait()
 await click('Enviar informes a todos')
 assert.equal(await js('window.examFixture.sends'), 0)
 assert.equal(await js(`document.querySelector('[role="alertdialog"]') !== null`), true)
 await click('Cancelar')
 assert.equal(await js('window.examFixture.sends'), 0)
 await click('Enviar informes a todos'); await click('Enviar informes')
 assert.equal(await js('window.examFixture.sends'), 1)
 assert.equal(await js(`document.querySelector('table').rows[1].textContent.includes('No entregado')`), true)
 assert.equal(await js(`document.querySelector('table').rows[1].cells[1].textContent`), '10,0')
 assert.equal(await js(`document.body.innerText.includes('Entregado')`), true)
 await shot('report-not-delivered-1366')
 await click('Reintentar no entregados')
 assert.equal(await js('window.examFixture.sends'), 1)
 await click('Enviar informes')
 assert.equal(await js('window.examFixture.sends'), 2)
 assert.equal(await js(`document.querySelector('table').rows[1].textContent.includes('Entregado')`), true)
 assert.equal(await js(`document.querySelector('table').rows[1].cells[1].textContent`), '10,0')
 await click('Exportar notas'); await click('CSV')
 assert.equal(await js(`window.examFixture.exported.includes('10,0')`), true)
 await click('Cerrar')
 await js('window.examFixture.history()'); await wait()
 assert.equal(await js(`document.querySelector('[aria-label="Sesiones de examen"]') !== null`), true)
 await shot('session-history-1366')
 await click('Abrir sesión')
 assert.equal(await js(`document.querySelector('[data-testid="final-grades"]') !== null`), true)
 await js('window.examFixture.history()'); await wait()
 await js(`(()=>{const d=[...document.querySelectorAll('details')].find(d=>d.querySelector('summary')?.textContent==='Consultar correcciones');d.querySelector('summary').click();d.querySelector('button').click()})()`); await wait()
 assert.equal(await js(`document.querySelector('.matrix-viewport') !== null`), true)
 await click('Notas finales')
 assert.equal(await js(`document.querySelector('[data-testid="final-grades"]') !== null`), true)

 assert.deepEqual(errors, [])
 writeFileSync(join(out, 'session-ui.json'), JSON.stringify({ viewports: [[1920,1080],[1366,768]], maximumAndLatest: 'verified', noGradeReason: 'verified', doubleClick: 'one finalization', sendConfirmation: 'before every send/retry', finalizedCountdown: 'absent', errors }, null, 2))
 console.log(`Session UI verified: ${out}`); win.destroy(); app.quit()
}).catch(error => { console.error(error); app.exit(1) })
