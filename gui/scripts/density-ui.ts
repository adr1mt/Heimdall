// Run from gui/ after build and bundling density-fixture.tsx. Uses a temporary profile.
import { app, BrowserWindow } from 'electron'
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { tmpdir } from 'node:os'
import assert from 'node:assert/strict'
const base = mkdtempSync(join(tmpdir(), 'heimdall-density-'))
const out = resolve(process.env.DENSITY_UI_OUT || '/tmp/heimdall-density-ui')
mkdirSync(out, { recursive: true })
app.setPath('userData', join(base, 'profile'))
app.disableHardwareAcceleration()
app.commandLine.appendSwitch('force-device-scale-factor', '1')
const css = readdirSync('out/renderer/assets').find((name) => name.startsWith('index-') && name.endsWith('.css'))!
writeFileSync(join(base, 'style.css'), readFileSync(join('out/renderer/assets', css)))
writeFileSync(join(base, 'fixture.js'), readFileSync('/tmp/heimdall-density-fixture.js'))
writeFileSync(join(base, 'index.html'), '<html><head><meta charset="utf-8"><link rel="stylesheet" href="style.css"></head><body><div id="root"></div><script src="fixture.js"></script></body></html>')
const wait = () => new Promise((r) => setTimeout(r, 300))
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1366, height: 768, show: false,
    webPreferences: { contextIsolation: true, nodeIntegration: false, offscreen: true, backgroundThrottling: false } })
  const errors: string[] = []
  win.webContents.on('console-message', (event) => { if (event.level === 'error') errors.push(event.message) })
  const js = (code: string) => win.webContents.executeJavaScript(code)
  const click = async (name: string, aria = false) => {
    await js(`(()=>{const b=[...document.querySelectorAll('button')].find(e=>${aria ? "e.getAttribute('aria-label')" : 'e.textContent.trim()'}===${JSON.stringify(name)});if(!b || b.disabled) throw Error('Missing button '+${JSON.stringify(name)});b.click()})()`)
    await wait()
  }
  const select = async (name: string, value: string) => {
    await js(`(()=>{const s=document.querySelector('select[aria-label="${name}"]');if(!s) throw Error('Missing select');s.value=${JSON.stringify(value)};s.dispatchEvent(new Event('change',{bubbles:true}))})()`)
    await wait()
  }
  const shot = async (name: string) => { await wait(); writeFileSync(join(out, `${name}.png`), (await win.webContents.capturePage()).toPNG()) }
  const proof: unknown[] = []
  await win.loadFile(join(base, 'index.html')); await wait()
  assert.ok(await js(`document.body.innerText.includes('7 aprobados') && document.body.innerText.includes('0 suspensos') && document.body.innerText.includes('7 sin evaluar')`))
  for (const [width, height] of [[1366, 768], [1024, 768]]) {
    win.setSize(width, height); await wait()
    assert.equal(await js(`document.querySelector('aside').dataset.collapsed`), String(width <= 1180))
    for (const zoom of [80, 100, 120]) {
      await js(`document.querySelector('.teacher-display').open=true`)
      await select('Escala de interfaz', String(zoom))
      await js(`document.querySelector('.teacher-display').open=false`)
      await click('Lista')
      const geometry = await js(`(()=>{const names=[...document.querySelectorAll('.student-name')];const r=names[0].getBoundingClientRect();return {names:names.length,firstRow:r.top,visibleRows:names.filter(n=>n.getBoundingClientRect().bottom<innerHeight).length,clipped:names.some(n=>n.scrollWidth>n.clientWidth+1 || n.scrollHeight>n.clientHeight+1),rootOverflow:document.documentElement.scrollWidth>innerWidth,font:getComputedStyle(document.documentElement).fontSize}})()`)
      assert.equal(geometry.names, 14)
      assert.equal(geometry.clipped, false, 'Full list names')
      assert.equal(geometry.rootOverflow, false)
      assert.ok(geometry.visibleRows >= 5, JSON.stringify(geometry))
      proof.push({ width, height, zoom, list: geometry })
      await shot(`list-${width}-${zoom}`)
      await click('Matriz')
      const matrix = await js(`(()=>{const v=document.querySelector('.matrix-viewport'),row=document.querySelector('tbody tr'),c=document.querySelector('.case-name');return {columns:document.querySelectorAll('thead th[data-column]').length,checkFont:getComputedStyle(c).fontSize,rowHeight:row.getBoundingClientRect().height,viewportWidth:v.clientWidth,horizontal:v.scrollWidth>v.clientWidth,rootOverflow:document.documentElement.scrollWidth>innerWidth,firstColumn:document.querySelector('col').getBoundingClientRect().width}})()`)
      assert.equal(matrix.columns, 14)
      assert.ok(matrix.horizontal)
      assert.equal(matrix.rootOverflow, false)
      assert.ok(matrix.rowHeight < 60 * zoom / 100, JSON.stringify(matrix))
      proof.push({ width, zoom, matrix })
      await shot(`matrix-${width}-${zoom}`)
    }
  }
  await js(`document.querySelector('.teacher-display').open=true`)
  await select('Escala de interfaz', '100')
  await select('Menú lateral', 'collapsed')
  await js(`document.querySelector('.teacher-display').open=false`)
  win.reload(); await wait()
  assert.equal(await js(`document.querySelector('aside').dataset.collapsed`), 'true', 'Sidebar survives reload')
  await click('Expandir menú lateral', true)
  assert.equal(await js(`document.querySelector('aside').dataset.collapsed`), 'false')
  await click('Contraer menú lateral', true)
  await js(`window.densityResults(50)`); await wait(); await click('Matriz')
  const before = await js(`(()=>{const v=document.querySelector('.matrix-viewport');v.focus();return v.getBoundingClientRect().top})()`)
  win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Right' }); win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Right' }); await wait()
  assert.ok(await js(`document.querySelector('.matrix-viewport').scrollLeft>0`), 'Keyboard scroll')
  await js(`(()=>{const v=document.querySelector('.matrix-viewport');v.scrollLeft=500;v.scrollTop=400})()`); await wait()
  const sticky = await js(`(()=>{const v=document.querySelector('.matrix-viewport').getBoundingClientRect(),h=document.querySelector('thead').getBoundingClientRect(),c=document.querySelector('tbody th').getBoundingClientRect();return {headerTop:h.top,left:c.left,viewportLeft:v.left}})()`)
  assert.ok(Math.abs(sticky.headerTop - before) < 3, JSON.stringify(sticky))
  assert.ok(Math.abs(sticky.left - sticky.viewportLeft) < 3, JSON.stringify(sticky))
  await shot('matrix-sticky-1024')
  await js(`window.densityResults();window.resultsRefresh('begin')`); await wait(); await click('Lista')
  assert.equal(await js(`document.querySelectorAll('.student-name').length`), 14)
  assert.ok(await js(`document.body.innerText.includes('pendientes de actualizar')`))
  await shot('refresh-1024')
  await js(`window.resultsRefresh('fail')`); await wait()
  assert.equal(await js(`document.querySelectorAll('.student-name').length`), 14)
  await js(`window.resultsRefresh('success');window.densityCorrect()`); await wait()
  assert.ok(await js(`document.querySelector('.pending-students').getBoundingClientRect().width > document.querySelector('main').clientWidth * 0.85`))
  await shot('correct-1024')
  await js(`window.densityCorrect(true)`); await wait()
  await shot('correct-progress-1024')
  await js(`window.densityResults();document.querySelector('.teacher-display').open=true`); await wait()
  await select('Escala de interfaz', '80')
  await js(`document.querySelector('.teacher-display').open=false;window.resultsProjector(true)`); await wait()
  assert.equal(await js(`getComputedStyle(document.documentElement).fontSize`), '20px', 'Independent projector scale')
  assert.ok(await js(`!document.querySelector('aside')`))
  await click('Matriz'); await click('Ajustar a pantalla'); await wait()
  const fit = await js(`(()=>{const c=document.querySelector('.projector-content'),v=c.parentElement,r=v.getBoundingClientRect(),last=document.querySelector('thead th:last-child').getBoundingClientRect();return {horizontal:v.scrollWidth-v.clientWidth,vertical:v.scrollHeight-v.clientHeight,lastRight:last.right,viewportRight:r.right}})()`)
  assert.ok(fit.horizontal <= 2 && fit.vertical <= 2 && fit.lastRight <= fit.viewportRight + 2, JSON.stringify(fit))
  proof.push({ projectorFit14: fit })
  await shot('projector-1024')
  await js(`window.resultsProjector(false)`); await wait()
  assert.equal(await js(`getComputedStyle(document.documentElement).fontSize`), '12.8px')
  await js(`document.querySelector('.teacher-display').open=true`); await click('Restablecer al 100 %')
  await js(`document.querySelector('.teacher-display').open=false;document.documentElement.classList.add('dark')`); await wait()
  await shot('matrix-dark-1024')
  assert.deepEqual(errors, [], 'No renderer errors')
  proof.push({ persistence: 'reload PASS', sidebar: 'automatic and manual PASS', sticky, keyboard: 'PASS', refresh: 'begin/failure PASS', projector: 'independent zoom and fit PASS' })
  writeFileSync(join(out, 'proof.json'), JSON.stringify(proof, null, 2))
  console.log(`Density evidence: ${out}`)
  app.exit(0)
}).catch((error) => { console.error(error); app.exit(1) })
